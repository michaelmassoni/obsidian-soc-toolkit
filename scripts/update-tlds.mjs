// Regenerates src/tlds.ts from IANA's list of top-level domains: `node scripts/update-tlds.mjs`
import { writeFileSync } from "fs";

const response = await fetch("https://data.iana.org/TLD/tlds-alpha-by-domain.txt");
if (!response.ok) {
    console.error(`Failed to download TLD list: ${response.status}`);
    process.exit(1);
}
const lines = (await response.text()).split("\n");
const version = lines[0].replace(/^#\s*/, "");
const tlds = lines.filter(line => line && !line.startsWith("#")).map(line => line.toLowerCase());

writeFileSync("src/tlds.ts", `// Generated by scripts/update-tlds.mjs from https://data.iana.org/TLD/tlds-alpha-by-domain.txt
// ${version}
export const TLDS = new Set('${tlds.join(" ")}'.split(' '));
`);
console.log(`Wrote ${tlds.length} TLDs`);
